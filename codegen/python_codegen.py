        '',
        '    Protein backbone dihedrals:',
        '        PHI: C(i-1) - N(i) - CA(i) - C(i)',
        '        PSI: N(i) - CA(i) - C(i) - N(i+1)',
        '        OMEGA: CA(i) - C(i) - N(i+1) - CA(i+1)',
