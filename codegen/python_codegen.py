class CodegenError(Exception):
    """Error during code generation."""
    pass


def _write_validated_python(filepath: Path, lines: list[str], description: str) -> None:
    """
    Validate and write generated Python code.

    Args:
        filepath: Where to write the file.
        lines: Lines of Python code to join and write.
        description: Human-readable description for error messages.

    Raises:
        CodegenError: If the generated code has syntax errors.
    """
    code = '\n'.join(lines)

    # Validate syntax before writing
    try:
        ast.parse(code)
    except SyntaxError as e:
        # Find the problematic line for context
        code_lines = code.split('\n')
        context_start = max(0, (e.lineno or 1) - 3)
        context_end = min(len(code_lines), (e.lineno or 1) + 2)
        context = '\n'.join(
            f"  {i+1:4d} | {line}"
            for i, line in enumerate(code_lines[context_start:context_end], start=context_start)
        )

        raise CodegenError(
            f"Generated code has syntax error in {description}:\n"
            f"  Line {e.lineno}: {e.msg}\n"
            f"  Context:\n{context}\n"
            f"  This is a bug in the code generator."
        ) from None

    filepath.write_text(code)
    print(f"Generated: {filepath.relative_to(filepath.parent.parent)}")


def generate_python_molecule(biochem_dir: Path) -> None:
    """Generate Python Molecule enum from MOLECULE_TYPES."""

    lines = [
        '"""',
        'Molecule type enumeration.',
        '',
        'Based on PDB/mmCIF entity types from wwPDB:',
        '- _entity.type: polymer, non-polymer, water, branched',
        '- _entity_poly.type: polypeptide(L/D), polyribonucleotide, etc.',
        '',
        'See: https://mmcif.wwpdb.org/dictionaries/mmcif_pdbx_v50.dic/Items/_entity_poly.type.html',
        '',
        'AUTO-GENERATED by codegen/generate.py - DO NOT EDIT MANUALLY.',
        '"""',
        '',
        'from enum import IntEnum',
        '',
        '',
        'class Molecule(IntEnum):',
        '    """',
        '    Types of molecules that can appear in a structure.',
        '',
        '    Used to classify chains by their molecular type, enabling',
        '    filtering and type-specific operations.',
        '    """',
        '',
    ]

    for idx, mt in enumerate(MOLECULE_TYPES):
        lines.append(f"    {mt.name} = {idx}  # {mt.description}")

    lines.extend([
        '',
        '',
        'def molecule_type(value: int) -> Molecule:',
        '    """',
        '    Convert an integer value to the corresponding Molecule type.',
        '',
        '    Args:',
        '        value: Integer representing molecule type.',
        '',
        '    Returns:',
        '        The corresponding Molecule enum value.',
        '',
        '    Raises:',
        '        ValueError: If value doesn\'t correspond to a known molecule type.',
        '    """',
        '    try:',
        '        return Molecule(value)',
        '    except ValueError as e:',
        '        raise ValueError(f"Unknown molecule type value: {value}") from e',
        '',
        '',
        '# Terminal atoms per molecule type: (start_atoms, end_atoms)',
        '# Used for filtering during chain building with AtomGroup.terminal()',
        'TERMINAL_ATOMS: dict[int, tuple[frozenset[str], frozenset[str]]] = {',
    ])

    # Generate TERMINAL_ATOMS dict entries
    for mol_type, (start_atoms, end_atoms) in TERMINAL_ATOMS.items():
        # Use double quotes for atom names containing apostrophes
        start_str = ', '.join(f'"{a}"' for a in sorted(start_atoms))
        end_str = ', '.join(f'"{a}"' for a in sorted(end_atoms))
        lines.append(f"    Molecule.{MOLECULE_TYPES[mol_type].name}: (frozenset({{{start_str}}}), frozenset({{{end_str}}})),")

    lines.extend([
        '}',
        '',
    ])

    _write_validated_python(
        biochem_dir / "_generated_molecule.py",
        lines,
        "Molecule enum"
    )


def generate_python_elements(biochem_dir: Path, elements: dict[str, int]) -> None:
    """
    Generate Python Element enum from elements dict.

    Args:
        biochem_dir: Output directory for generated file.
        elements: Dictionary mapping element symbol (uppercase) to atomic number.
                  Loaded from PubChem via elements.load_elements().
    """
    lines = [
        '"""',
        'Chemical element definitions.',
        '',
        'AUTO-GENERATED by ciffy/src/codegen/generate.py - DO NOT EDIT MANUALLY.',
        'Source: PubChem Periodic Table (https://pubchem.ncbi.nlm.nih.gov)',
        '"""',
        '',
        'from enum import IntEnum',
        '',
        '',
        'class Element(IntEnum):',
        '    """',
        '    Chemical elements with their atomic numbers.',
        '',
        '    Values correspond to atomic numbers for common biological elements.',
        '    """',
        '',
    ]

    # Group elements by category for readability
    organic = ["H", "C", "N", "O", "P", "S"]
    halogens = ["F", "CL", "BR", "I"]
    alkali = ["LI", "NA", "K", "RB", "CS"]
    alkaline = ["MG", "CA", "SR", "BA"]
    transition = ["MN", "FE", "CO", "NI", "CU", "ZN", "MO", "AG", "CD", "W", "PT", "AU", "HG"]
    other = ["AL", "SE", "PB"]

    def write_group(name: str, symbols: list[str]) -> None:
        lines.append(f"    # {name}")
        for sym in symbols:
            if sym in elements:
                lines.append(f"    {sym} = {elements[sym]}")
        lines.append("")

    write_group("Common organic elements", organic)
    write_group("Halogens", halogens)
    write_group("Alkali metals", alkali)
    write_group("Alkaline earth metals", alkaline)
    write_group("Transition metals", transition)
    write_group("Other elements", other)

    lines.extend([
        '',
        '# Pre-computed reverse lookup: atomic number -> element name',
        'ELEMENT_NAMES: dict[int, str] = {e.value: e.name for e in Element}',
        '',
    ])

    _write_validated_python(
        biochem_dir / "_generated_elements.py",
        lines,
        "Element enum"
    )


